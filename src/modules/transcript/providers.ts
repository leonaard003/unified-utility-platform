interface RawCaptionTrack {
  baseUrl: string;
  languageCode: string;
  name: string;
  kind?: string;
}

const INNERTUBE_KEY = 'AIzaSyAO_FJ2SlqU8Q4STEHLGCilw_Y9_11qcW8';

/**
 * InnerTube clients worth trying, cheapest/most-permissive first. YouTube
 * rotates which ones serve anonymous requests, so we try several rather than
 * betting the module on one.
 */
const INNERTUBE_CLIENTS = [
  { clientName: 'ANDROID', clientVersion: '19.09.37', androidSdkVersion: 30 },
  { clientName: 'WEB', clientVersion: '2.20240304.00.00' },
  { clientName: 'MWEB', clientVersion: '2.20240304.00.00' },
  { clientName: 'TVHTML5_SIMPLY_EMBEDDED_PLAYER', clientVersion: '2.0' },
] as const;

interface PlayerProbe {
  tracks: RawCaptionTrack[];
  title?: string;
  /** Reason the attempt produced nothing, for honest error reporting. */
  reason?: string;
}

function readTracks(payload: unknown): RawCaptionTrack[] {
  const renderer = (payload as { captions?: { playerCaptionsTracklistRenderer?: { captionTracks?: unknown } } })
    ?.captions?.playerCaptionsTracklistRenderer?.captionTracks;
  if (!Array.isArray(renderer)) return [];
  return renderer
    .map((raw) => {
      const t = raw as { baseUrl?: string; languageCode?: string; kind?: string; name?: { simpleText?: string; runs?: { text: string }[] } };
      const label = t.name?.simpleText ?? t.name?.runs?.map((r) => r.text).join('') ?? t.languageCode ?? 'Unknown';
      return { baseUrl: t.baseUrl ?? '', languageCode: t.languageCode ?? 'unknown', name: label, kind: t.kind };
    })
    .filter((t) => t.baseUrl !== '');
}

async function probeInnertube(videoId: string): Promise<PlayerProbe> {
  const reasons: string[] = [];
  for (const client of INNERTUBE_CLIENTS) {
    const body = JSON.stringify({
      context: { client: { ...client, hl: 'en', gl: 'US' } },
      videoId,
      contentCheckOk: true,
      racyCheckOk: true,
    });
    const { body: text } = await fetchText(`https://www.youtube.com/youtubei/v1/player?key=${INNERTUBE_KEY}`, {
      method: 'POST',
      body,
      headers: { 'content-type': 'application/json' },
    });
    let payload: unknown;
    try {
      payload = JSON.parse(text);
    } catch {
      reasons.push(`${client.clientName}: response was not JSON`);
      continue;
    }
    const status = (payload as { playabilityStatus?: { status?: string; reason?: string } }).playabilityStatus;
    const tracks = readTracks(payload);
    if (tracks.length > 0) {
      const title = (payload as { videoDetails?: { title?: string } }).videoDetails?.title;
      return { tracks, title };
    }
    reasons.push(`${client.clientName}: ${status?.status ?? 'no captions'}${status?.reason ? ` (${status.reason})` : ''}`);
  }
  return { tracks: [], reason: reasons.join('; ') };
}

async function probeWatchPage(videoId: string): Promise<PlayerProbe> {
  const { body } = await fetchText(watchUrl(videoId));
  const match = /"captionTracks":(\[.*?\])(?=,")/s.exec(body);
  if (!match) {
    const blocked = /Sign in to confirm|consent\.youtube\.com|not a bot/i.test(body);
    return { tracks: [], reason: blocked ? 'watch page: YouTube asked this server to sign in' : 'watch page: no caption track list present' };
  }
  try {
    return { tracks: readTracks({ captions: { playerCaptionsTracklistRenderer: { captionTracks: JSON.parse(match[1]!) } } }) };
  } catch {
    return { tracks: [], reason: 'watch page: caption track list could not be parsed' };
  }
}

function pickTrack(tracks: RawCaptionTrack[], languageHint?: string): RawCaptionTrack {
  if (languageHint) {
    const exact = tracks.find((t) => t.languageCode.toLowerCase() === languageHint.toLowerCase());
    if (exact) return exact;
    const prefix = tracks.find((t) => t.languageCode.toLowerCase().startsWith(languageHint.slice(0, 2).toLowerCase()));
    if (prefix) return prefix;
  }
  const manualEnglish = tracks.find((t) => t.languageCode.startsWith('en') && t.kind !== 'asr');
  if (manualEnglish) return manualEnglish;
  const anyEnglish = tracks.find((t) => t.languageCode.startsWith('en'));
  if (anyEnglish) return anyEnglish;
  const anyManual = tracks.find((t) => t.kind !== 'asr');
  return anyManual ?? tracks[0]!;
}

export const liveProvider: TranscriptProvider = {
  id: 'live',
  label: 'Live fetch',
  description:
    'Requests the real caption track straight from YouTube with no API key. Works when YouTube serves this server anonymously.',

  async fetchTranscript(videoId, languageHint) {
    let probe = await probeInnertube(videoId);
    if (probe.tracks.length === 0) {
      const fallback = await probeWatchPage(videoId);
      probe = fallback.tracks.length > 0 ? fallback : { tracks: [], reason: [probe.reason, fallback.reason].filter(Boolean).join(' | ') };
    }

    if (probe.tracks.length === 0) {
      logger.warn('transcript.live_unavailable', { videoId, reason: probe.reason });
      throw new AppError('UPSTREAM_BLOCKED', 'YouTube did not return a caption track for this video.', {
        hint:
          `Upstream said: ${probe.reason || 'no detail given'}. ` +
          'Either the video genuinely has no captions, or YouTube is refusing anonymous requests from this server ' +
          '(common on VPS/datacenter IPs). Switch to Demo mode to exercise the exports, or paste a caption file below.',
      });
    }

    const track = pickTrack(probe.tracks, languageHint);
    // json3 is the most reliable modern format; fall back to the default XML.
    const attempts = [`${track.baseUrl}&fmt=json3`, track.baseUrl];
    for (const url of attempts) {
      const { body } = await fetchText(url);
      const { segments } = parseCaptions(body);
      if (segments.length > 0) {
        return {
          videoId,
          mode: 'live',
          isDemo: false,
          language: track.name,
          languageCode: track.languageCode,
          autoGenerated: track.kind === 'asr',
          availableTracks: probe.tracks.map((t) => ({
            languageCode: t.languageCode,
            label: t.name,
            autoGenerated: t.kind === 'asr',
          })),
          segments,
          title: probe.title,
          provenance: `Fetched live from YouTube — track "${track.name}" (${track.languageCode}${track.kind === 'asr' ? ', auto-generated' : ''}).`,
        };
      }
    }

    throw new AppError('UPSTREAM_BLOCKED', 'YouTube listed a caption track but returned no text for it.', {
      hint: 'This usually means the track was withdrawn between the two requests. Try again in a moment.',
    });
  },
};

