import { AppError } from '@/lib/errors';
import { OUTBOUND_TIMEOUT_MS } from '@/lib/limits';
import { logger } from '@/lib/logger';
import { parseCaptions, watchUrl, type TranscriptSegment } from './youtube';

/**
 * Transcript source layer.
 *
 * Two providers implement the same interface:
 *
 *  - `liveProvider`  — a real, unauthenticated YouTube caption fetch (InnerTube
 *    player endpoint, then a watch-page scrape as a fallback). No API key and no
 *    extra npm dependency. It genuinely works from residential IPs; YouTube
 *    frequently answers `LOGIN_REQUIRED` from datacenter/VPS ranges, in which
 *    case this provider FAILS LOUDLY instead of inventing content.
 *
 *  - `demoProvider` — a fixed, clearly-labelled sample transcript for trying the
 *    UI, the export formats and the downstream flow. It never claims to be the
 *    captions of the requested video.
 *
 * To add a real production source later (a caption API, a yt-dlp worker, a
 * proxy pool), implement `TranscriptProvider` and register it in `PROVIDERS`.
 * Nothing else in the app needs to change.
 */

export type TranscriptMode = 'live' | 'demo';

export interface TranscriptTrack {
  languageCode: string;
  label: string;
  autoGenerated: boolean;
}

export interface TranscriptResult {
  videoId: string;
  mode: TranscriptMode;
  /** True when the text is sample content rather than the video's captions. */
  isDemo: boolean;
  language: string;
  languageCode: string;
  autoGenerated: boolean;
  /** Every caption track the source reported, when it reported any. */
  availableTracks: TranscriptTrack[];
  segments: TranscriptSegment[];
  /** Human-readable provenance shown in the UI above the transcript. */
  provenance: string;
  title?: string;
  platform?: string;
  sourceUrl?: string;
  engine?: string;
}

export interface TranscriptProvider {
  id: TranscriptMode;
  label: string;
  description: string;
  fetchTranscript(videoId: string, languageHint?: string): Promise<TranscriptResult>;
}

const BROWSER_UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122.0.0.0 Safari/537.36';

async function fetchText(url: string, init: RequestInit = {}): Promise<{ ok: boolean; status: number; body: string }> {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), OUTBOUND_TIMEOUT_MS);
  try {
    const response = await fetch(url, {
      ...init,
      signal: controller.signal,
      headers: {
        'user-agent': BROWSER_UA,
        'accept-language': 'en-US,en;q=0.9',
        ...(init.headers as Record<string, string> | undefined),
      },
      cache: 'no-store',
    });
    return { ok: response.ok, status: response.status, body: await response.text() };
  } catch (err) {
    if (err instanceof Error && err.name === 'AbortError') {
      throw new AppError('TIMEOUT', 'YouTube did not answer in time.', {
        hint: `The request was cancelled after ${Math.round(OUTBOUND_TIMEOUT_MS / 1000)}s. Try again.`,
      });
    }
    throw new AppError('UPSTREAM_BLOCKED', 'Could not reach YouTube from this server.', {
      hint: err instanceof Error ? err.message : 'Check the server network connection.',
    });
  } finally {
    clearTimeout(timer);
  }
}

