export const PROVIDERS: Record<TranscriptMode, TranscriptProvider> = {
  live: liveProvider,
  demo: demoProvider,
};

export function describeProviders() {
  return (Object.keys(PROVIDERS) as TranscriptMode[]).map((id) => ({
    id,
    label: PROVIDERS[id].label,
    description: PROVIDERS[id].description,
    returnsRealCaptions: id === 'live',
  }));
}
